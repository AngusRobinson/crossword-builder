"""Turn experiment/results.jsonl into experiment/FINDINGS.md.

Screening asks which parameters move anything and whether the answer differs by
style. So the report is arranged that way: one table per metric, parameters
down the side, styles across, and the baseline configuration called out
separately for comparison.

Nothing here decides anything. A difference that looks real goes to a focused
paired comparison on the tune lists that screening did not use, and only then
to the held-out half. See DESIGN.md.
"""

import json
import os
import statistics as s
import sys
from collections import defaultdict

if os.path.basename(os.getcwd()) == "experiment":
    os.chdir("..")

STYLES = ("british", "barred", "jumbo", "us")
BUDGETS = (5, 10, 20, 40)


def coverage_of(row):
    """Targets seated as a fraction of what the best grid could hold."""
    return row["seated"] / row["ceiling"] if row["ceiling"] else 0.0


def at_budget(row, seconds):
    """What this run had achieved by `seconds`, from its recorded curve."""
    best = 0
    for moment, seated, _ok, _q in row["curve"]:
        if moment <= seconds:
            best = max(best, seated)
    return best / row["ceiling"] if row["ceiling"] else 0.0


def table(rows, key, values, metric, label, out):
    out.append(f"\n### {label}\n")
    out.append("| " + key + " | " + " | ".join(STYLES) + " | all |")
    out.append("|" + "---|" * (len(STYLES) + 2))
    for value in values:
        cells = []
        for style in STYLES:
            got = [metric(r) for r in rows
                   if r["style"] == style and r["config"][key] == value]
            cells.append(f"{s.mean(got):.3f}" if got else "-")
        every = [metric(r) for r in rows if r["config"][key] == value]
        cells.append(f"**{s.mean(every):.3f}**" if every else "-")
        out.append(f"| {value} | " + " | ".join(cells) + " |")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "experiment/results.jsonl"
    rows = [json.loads(line) for line in open(path, encoding="utf-8")]
    if not rows:
        raise SystemExit("no results yet")
    configs = {r["config_id"] for r in rows}
    keys = sorted(rows[0]["config"])

    out = ["# Parameter study: findings", "",
           "Generated by `experiment/analyse.py`. The design, the priors and "
           "the rules for adopting anything are in [DESIGN.md](DESIGN.md), "
           "which was written first.", "",
           f"{len(rows):,} runs over {len(configs)} configurations, "
           f"{len({r['list'] for r in rows})} lists.", ""]

    # How the defaults did, against everything else tried.
    base = [r for r in rows if r["config_id"] == 0]
    rest = [r for r in rows if r["config_id"] != 0]
    out.append("## Today's defaults against the field\n")
    out.append("| style | defaults: coverage | complete | field: coverage | complete |")
    out.append("|---|---|---|---|---|")
    for style in STYLES:
        b = [r for r in base if r["style"] == style]
        f = [r for r in rest if r["style"] == style]
        if not b or not f:
            continue
        out.append(
            f"| {style} | {s.mean([coverage_of(r) for r in b]):.3f} | "
            f"{sum(r['ok'] for r in b)}/{len(b)} | "
            f"{s.mean([coverage_of(r) for r in f]):.3f} | "
            f"{sum(r['ok'] for r in f) / len(f):.0%} |")

    # The headline: which parameters move coverage, and where.
    out.append("\n## Coverage, by parameter and style\n")
    out.append("Targets seated as a fraction of the achievable ceiling. A "
               "parameter whose rows differ little is one that does not matter.")
    for key in keys:
        values = sorted({r["config"][key] for r in rows})
        table(rows, key, values, coverage_of, f"`{key}`", out)

    # What more time buys, read off the recorded curves.
    out.append("\n## What more time buys\n")
    out.append("Coverage reached by each budget, from the improvement curves. "
               "One run gives every budget below its own, exactly.\n")
    out.append("| style | " + " | ".join(f"{b}s" for b in BUDGETS) + " | final |")
    out.append("|" + "---|" * (len(BUDGETS) + 2))
    for style in STYLES:
        sub = [r for r in rows if r["style"] == style]
        if not sub:
            continue
        cells = [f"{s.mean([at_budget(r, b) for r in sub]):.3f}" for b in BUDGETS]
        cells.append(f"{s.mean([coverage_of(r) for r in sub]):.3f}")
        out.append(f"| {style} | " + " | ".join(cells) + " |")

    # Completion and familiarity, so a coverage win that costs elsewhere shows.
    out.append("\n## Completion rate, by parameter and style\n")
    for key in keys:
        values = sorted({r["config"][key] for r in rows})
        table(rows, key, values, lambda r: float(r["ok"]), f"`{key}`", out)

    out.append("\n## Fill familiarity, by parameter and style\n")
    out.append("Completed grids only.\n")
    done = [r for r in rows if r["ok"]]
    for key in keys:
        values = sorted({r["config"][key] for r in done})
        table(done, key, values, lambda r: r["quality"], f"`{key}`", out)

    with open("experiment/FINDINGS.md", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")
    print(f"experiment/FINDINGS.md: {len(rows):,} runs, {len(configs)} configs")


if __name__ == "__main__":
    main()
